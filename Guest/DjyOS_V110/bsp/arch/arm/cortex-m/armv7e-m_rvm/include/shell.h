struct shellinfo
{
   const char *sh_Tab_start; //
   const char *sh_Tab_end; //
};

struct shell_list
{
    list_t list;
    struct shellinfo info;
};
#define PARAMETER_MAX     (10)   //maximum number of parameters

/* A routine shell function and an expanded shell function differ in whether
 * the arguments are parsed inside or outside the function.  The help text and
 * the data variables are mostly a matter of trimming: the tool decides which
 * kinds of shell entries are linked in. */

struct shell_cmd
{
    void *shell_fun_addr;
    char *shell_help_addr;
};
#define DJYSH_HELP_NAME "djysh_"

#if(CFG_MODULE_ENABLE_SHELL == true)
#define ADD_TO_ROUTINE_SHELL(cmdname,fun,help) \
                __attribute__((section(".ro_shell_cmd")))\
                const struct shell_cmd djysh_##cmdname = \
                        {.shell_fun_addr  = fun,.shell_help_addr = help,}

#define ADD_TO_EXPAND_SHELL(cmdname,fun,help) \
                __attribute__((section(".ex_shell_cmd")))\
                const struct shell_cmd djysh_##cmdname = \
                        {.shell_fun_addr  = fun,.shell_help_addr = help,}

//usage: "ADD_TO_IN_SHELL_DATA u32 sh;" - expose sh as a shell variable
#define ADD_TO_IN_SHELL_DATA  __attribute__((section(".ro_shell_data")))//routine shell data
#define ADD_TO_EX_SHELL_DATA    __attribute__((section(".ex_shell_data")))//expanded shell data

#else   //for #if(CFG_MODULE_ENABLE_SHELL == true)

//the shell component is off: every macro expands to nothing
#define ADD_TO_ROUTINE_SHELL(cmdname,fun,help)
#define ADD_TO_EXPAND_SHELL(cmdname,fun,help)
#define ADD_TO_IN_SHELL_DATA
#define ADD_TO_EX_SHELL_DATA

#endif   //for #if(CFG_MODULE_ENABLE_SHELL == true)

// ============================================================================
