// Return  : the extracted argument;
// Notes   : arguments are separated by spaces;
//           the separator after the extracted argument is replaced by '\0',
//           so the input buffer is modified in place;
// ============================================================================
char *shell_inputs(char *input, char **next);
void shell_GetStrFromStdio(char *buf,u32 limit);

